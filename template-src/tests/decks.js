// Decks (engine 2026-11q; rule 2.2): one pre-test and post-test per deck, one mini-quiz numbering, delayed test over all decks.
// Usage: node decks.js <base url> (serves decks.html: 2 decks, rounds 1-2 in deck 1 and round 3 in deck 2, SHEET_URL example.invalid;
// decksbad.html: author check)
const {chromium}=require('playwright'); const base=process.argv[2]+'/decks.html', bad=process.argv[2]+'/decksbad.html';
const out=[]; const ok=(c,m)=>out.push((c?'PASS ':'FAIL ')+m);
const rec=t=>({raw:{ans:[],conf:[]},qs:[],auto:50,self:{},fb:null,mp:null,sent:true,t});
const mrec=t=>({raw:{ans:[0,0,0],ms:[1000,1000,1000],ok:[1,1,1],conf:[]},qs:[1,1,1],auto:3,self:{},fb:null,mp:null,sent:true,t});
const D=864e5;
(async()=>{ const b=await chromium.launch(); const ctx=await b.newContext({viewport:{width:390,height:844}});
  const posts=[], gets=[];
  await ctx.route(/example\.invalid/,r=>{ const q=r.request(); if(q.method()==='POST') posts.push(JSON.parse(q.postData())); else gets.push(q.url());
    r.fulfill({status:200,contentType:'application/json',headers:{'access-control-allow-origin':'*'},body:'{"ok":true,"top":[],"items":[],"n":0}'}); });
  await ctx.route(/fonts\./,r=>r.abort());
  const p=await ctx.newPage(); const errs=[], cerr=[]; p.on('pageerror',e=>errs.push(e.message+' @'+p.url()+' '+(e.stack||'').split('\n').slice(1,4).join(' '))); p.on('console',m=>{ if(m.type()==='error'&&!/Failed to load resource/.test(m.text())) cerr.push(m.text()); });
  p.on('dialog',d=>d.accept());
  const seed=async(st,hash)=>{ await p.evaluate(st=>{ localStorage.clear(); localStorage.setItem('sim-code','"PHY-7KQ2"'); localStorage.setItem('sim-program','"tip-tr"');
      if(st) localStorage.setItem('tpl-t4',JSON.stringify(st)); },st);
    await p.goto('about:blank'); await p.goto(base+'#'+(hash||'now')); await p.waitForTimeout(300); };   // a new page load: no record of the previous seed stays in memory
  const hash=()=>new URL(p.url()).hash;
  const nextTxt=async()=>(await p.$('.nownext'))?(await p.textContent('.nownext')).trim():'';
  const txt=async s=>(await p.$(s))?(await p.textContent(s)):'';
  const t0=Date.now(); const items=()=>p.$$eval('#quiz .q',e=>e.filter(x=>/^q\d+$/.test(x.id)).length);
  await p.goto(base+'#now'); await seed(null);
  ok(!cerr.length,'author check: no console error for 2 correct decks '+cerr.join(' | '));
  const modes=await p.$$eval('#qmode button',e=>e.map(x=>x.textContent.trim()));
  ok(modes.join('|')==='Şimdi|Ön test 1|Mini quiz|Son test 1|Ön test 2|Son test 2|Gecikmeli test','mode buttons: '+modes.join(' · '));
  ok(await p.$$eval('.nowdeck',e=>e.map(x=>x.textContent).join('|'))==='Bölüm 1: Geri bildirim|Bölüm 2: Akım','Now page: one block per deck with its title');
  ok(JSON.stringify(await p.$$eval('.nowrounds',e=>e.map(x=>[...x.querySelectorAll('[data-r]')].map(c=>+c.dataset.r))))==='[[1,2],[3]]','round chips per deck: deck 1 = 1, 2; deck 2 = 3 (one numbering)');
  ok(/Sıradaki: Ön test 1/.test(await nextTxt()),'nothing done: next = Ön test 1 ('+await nextTxt()+')');
  await p.click('.nownext'); await p.waitForTimeout(200);
  ok(hash()==='#pre1'&&/Bölüm 1: Geri bildirim/.test(await txt('.deckhead')),'next opens #pre1 with the deck title');
  await p.goto(base+'#pre'); await p.waitForTimeout(200);
  ok(hash()==='#pre1','old link #pre = deck 1 (address #pre1)');
  await p.goto(base+'#post2'); await p.waitForTimeout(200);
  ok(hash()==='#post2'&&(await p.getAttribute('#qmode button[data-m="post"][data-d="1"]','aria-pressed'))==='true'&&/Bölüm 2/.test(await txt('.deckhead')),'#post2 opens the post-test of deck 2');
  ok(await items()===6,'a deck test has the deck\'s 6 items');
  await seed({pre1:rec(t0)});
  ok(/Sıradaki: Mini quiz 1/.test(await nextTxt()),'pre 1 done: next = Mini quiz 1');
  await seed({pre1:rec(t0),mid1:mrec(t0),mid2:mrec(t0)});
  ok(/Sıradaki: Son test 1/.test(await nextTxt()),'deck 1 rounds done: next = Son test 1');
  await seed({mid1:mrec(t0),post1:rec(t0)});
  ok(/Sıradaki: Ön test 2/.test(await nextTxt()),'post 1 done: next = Ön test 2');
  ok(await p.$eval('.nowrounds [data-r="2"]',e=>e.classList.contains('closed'))&&!(await p.$eval('.nowrounds [data-r="3"]',e=>e.classList.contains('closed'))),'after post 1: round 2 (deck 1) closed, round 3 (deck 2) open');
  ok(await p.isHidden('#qlate'),'after post 1 only: no reminder box (Q2-A)');
  ok(/«Bölüm 2: Akım» son testinden sonra/.test(await txt('.nowlist li:last-child')),'delayed row: opens after the post-test of the last deck');
  ok(/Son test 1: 54\/100/.test(await txt('#qcmp')),'compare pill names the deck (Son test 1: 54/100)');
  await p.goto(base+'#mid2'); await p.waitForTimeout(200);
  ok(/mini quiz turları kapandı/.test(await txt('#quiz')),'#mid2 after post 1: closed');
  await p.goto(base+'#mid3'); await p.waitForTimeout(200);
  ok(/Tur 3\/3/.test(await txt('.kh'))&&!!(await p.$('#kstart')),'#mid3 (deck 2) is open: Tur 3/3');
  await p.goto(base+'#pre1'); await p.waitForTimeout(200);
  ok(/ön test kapandı/.test(await txt('#quiz')),'#pre1 closed after post 1');
  await p.goto(base+'#pre2'); await p.waitForTimeout(200);
  ok(!!(await p.$('#qsubmit')),'#pre2 open');
  await p.goto(base+'#late'); await p.waitForTimeout(200);
  ok(/«Bölüm 2: Akım» son testinden 14 gün sonra/.test(await txt('#quiz')),'#late before the last post-test: opens 14 days after the last deck\'s post-test');
  await p.goto(base+'#mini'); await p.waitForTimeout(200);
  ok(await p.$$eval('[data-kr]',e=>e.length)===3&&/Tur 1\/3/.test(await txt('.kround')),'list of rounds: 3 rounds, one numbering');
  // sending: pre 2 through the page
  await seed({pre1:rec(t0),post1:rec(t0)},'pre2');
  await p.check('#r-pre-0-1'); await p.click('#qsubmit'); await p.waitForTimeout(150); await p.click('#qforce'); await p.waitForTimeout(200);
  posts.length=0; await p.click('#qsend'); await p.waitForTimeout(400);
  const P2=posts[0]||{}; const col=(x,n)=>((x.cols||[]).find(c=>c[0]===n)||[])[1];
  ok(P2.course==='template-d2'&&P2.test==='pre','pre 2 goes to tab template-d2, Test = pre');
  ok(col(P2,'Q1 mcq (4)')===4&&col(P2,'Total (100)')===8&&col(P2,'Program')==='tip-tr','pre 2 row: item score, total 8/100 (4 + gift), program');
  ok(hash()==='#pre2'&&(await p.getAttribute('#qmode button[data-m="pre"][data-d="1"]','aria-pressed'))==='true','address and button stay on deck 2');
  // post 1 (not the last deck): M2 and M7 columns empty (Q3-A); form columns sent
  await seed({pre1:rec(t0)},'post1');
  await p.check('#r-post-0-1'); await p.click('#qsubmit'); await p.waitForTimeout(150); await p.click('#qforce'); await p.waitForTimeout(200);
  ok(await p.isVisible('#fbform'),'post 1: feedback form shown (every deck)');
  ok(await p.isHidden('#qlate'),'post 1: no reminder box (only after the last deck)');
  ok(/«Bölüm 2: Akım» son testinden 14 gün sonra/.test(await txt('#qnote')),'post 1 note: delayed test after the last deck');
  posts.length=0; await p.click('#qsend'); await p.waitForTimeout(400);
  const P1=posts[0]||{};
  ok(P1.course==='template-d1'&&P1.test==='post','post 1 goes to tab template-d1, Test = post');
  const codes=[col(P1,'Item codes'),col(P2,'Item codes')];
  ok(codes[0]&&codes[1]&&codes[0]!==codes[1],'deck 2 sends its own item codes (they differ from deck 1)');
  ok(col(P1,'M2 answers')===null&&col(P1,'M7 stars')===null&&(P1.cols||[]).some(c=>/^Feedback:/.test(c[0])&&c[1]!==null),'post 1: M2 and M7 columns created empty, form columns filled');
  await seed({pre1:rec(t0),post1:rec(t0),pre2:rec(t0)},'post2');
  await p.check('#r-post-0-1'); await p.click('#qsubmit'); await p.waitForTimeout(150); await p.click('#qforce'); await p.waitForTimeout(200);
  ok(await p.isVisible('#qlate'),'post 2 (last deck): reminder box shown');
  posts.length=0; await p.click('#qsend'); await p.waitForTimeout(400);
  const P3=posts[0]||{};
  ok(P3.course==='template-d2'&&typeof col(P3,'M2 answers')==='string'&&typeof col(P3,'M7 stars')==='string','post 2: tab template-d2, M2 and M7 sent');
  // delayed test
  await seed({post1:rec(t0-20*D),post2:rec(t0-10*D)},'late');
  ok(/tarihinde açılacak/.test(await txt('#quiz')),'10 days after the last post-test: delayed test not open yet');
  await seed({post1:rec(t0-15*D)},'now');
  ok(/açık/.test(await txt('.nowlist li:last-child')),'last deck missed: the delayed test opens 14 days after the latest post-test taken');
  await seed({post1:rec(t0-20*D),post2:rec(t0-15*D)},'late');
  ok(await items()===12&&!(await p.$('.deckhead')),'delayed test: 12 items (all decks), no deck title');
  await p.check('#r-late-0-1'); await p.check('#cf-late-0-1'); await p.check('#r-late-6-1'); await p.click('#qsubmit'); await p.waitForTimeout(150); await p.click('#qforce'); await p.waitForTimeout(200);
  const res=await txt('#qres');
  ok(/9\/100/.test(res)&&/Bölüm 1: Geri bildirim: 10\/100/.test(res)&&/Bölüm 2: Akım: 8\/100/.test(res),'delayed total = mean of the parts: (10 + 8) / 2 = 9 ('+res.trim()+')');
  posts.length=0; await p.click('#qsend'); await p.waitForTimeout(400);
  const PL=posts[0]||{};
  ok(PL.course==='template-late'&&PL.test==='late','delayed test goes to tab template-late, Test = late');
  ok(col(PL,'Q12 order (24)')===0&&col(PL,'Auto total (168)')===8&&col(PL,'Part d1 (100)')===10&&col(PL,'Part d2 (100)')===8&&col(PL,'Total (100)')===9,'delayed row: Q1–Q12, Auto total (168), Part d1 10, Part d2 8, Total 9');
  ok(col(PL,'Item codes')===codes[0]+' '+codes[1],'delayed row: item codes of both decks');
  await p.goto(base+'#now'); await p.waitForTimeout(200);
  ok(/Gecikmeli test: 9\/100/.test(await txt('#qcmp')),'compare pill of the delayed test: 9/100');
  // class summary and board
  gets.length=0; await p.goto(base+'#summary2'); await p.waitForTimeout(500);
  ok(gets.some(u=>/summary=template-d2&test=pre/.test(u))&&hash()==='#summary2'&&/Bölüm 2: Akım/.test(await txt('#board h2')),'#summary2 reads tab template-d2, title names the deck');
  await p.click('#bclose'); await p.waitForTimeout(200);
  gets.length=0; await p.goto(base+'#summary'); await p.waitForTimeout(500);
  ok(gets.some(u=>/summary=template-d1&test=pre/.test(u))&&hash()==='#summary1','#summary = deck 1 (#summary1, tab template-d1)');
  await p.click('#bclose'); await p.waitForTimeout(200);
  gets.length=0; await p.goto(base+'#board3'); await p.waitForTimeout(500);
  ok(gets.some(u=>/board=template-quiz&test=mid3/.test(u)),'#board3: board of round 3 (one quiz tab)');
  await p.click('#bclose'); await p.waitForTimeout(200);
  // English, width, reset
  await seed(null);
  await p.click('#lang button[data-l="en"]'); await p.waitForTimeout(200);
  ok(/Next: Pre-test 1/.test(await nextTxt())&&/Part 1: Feedback/.test(await txt('.nowdeck')),'English: "Pre-test 1" and English deck titles');
  await p.click('#lang button[data-l="tr"]'); await p.waitForTimeout(100);
  ok(await p.evaluate(()=>document.documentElement.scrollWidth<=document.documentElement.clientWidth),'390 px: no sideways scroll');
  await seed({pre1:rec(t0),post2:rec(t0),late:rec(t0)});
  await p.goto(base+'#test-sifirla'); await p.waitForTimeout(300);
  const st=await p.evaluate(()=>JSON.parse(localStorage.getItem('tpl-t4')));
  ok(st&&st.pre1===null&&st.post2===null&&st.late===null&&'mid3' in st,'#test-sifirla clears the deck tests');
  ok(!errs.length,'no page errors '+errs.join(' | '));
  // author check
  const p2=await ctx.newPage(); const bad_=[]; p2.on('console',m=>{ if(m.type()==='error') bad_.push(m.text()); });
  await p2.goto(bad); await p2.waitForTimeout(300);
  ok(bad_.some(x=>/DECKS\[1\]: key used twice/.test(x))&&bad_.some(x=>/DECKS\[1\]: title needs tr and en/.test(x)),'author check names a key used twice and a title without en');
  await b.close(); console.log(out.join('\n'));
})().catch(e=>{console.log(out.join('\n')+'\nCRASH '+e.message); process.exit(1);});
