// "Şimdi / Now" page (engine 2026-11k): one QR per lecture opens #now; the next step is suggested.
// Usage: node now.js <base url> (serves midon.html: 2 mini-quiz rounds, all tests on, SHEET_URL example.invalid)
const {chromium}=require('playwright'); const base=process.argv[2]+'/midon.html';
const out=[]; const ok=(c,m)=>out.push((c?'PASS ':'FAIL ')+m);
const rec=t=>({raw:{ans:[],conf:[]},qs:[],auto:50,self:{},fb:null,mp:null,sent:true,t});
const mrec=t=>({raw:{ans:[0,0,0],ms:[1000,1000,1000],ok:[1,1,1],conf:[]},qs:[1,1,1],auto:3,self:{},fb:null,mp:null,sent:true,t});   // a sent mini-quiz round
(async()=>{ const b=await chromium.launch(); const ctx=await b.newContext({viewport:{width:390,height:844}});
  await ctx.route(/example\.invalid/,r=>r.fulfill({status:200,body:'{"ok":true,"rows":[],"n":0}'}));
  await ctx.route(/fonts\./,r=>r.abort());
  const p=await ctx.newPage(); const errs=[]; p.on('pageerror',e=>errs.push(e.message));
  const seed=async(st,run)=>{ await p.evaluate(([st,run])=>{ localStorage.clear(); localStorage.setItem('sim-code','"PHY-7KQ2"'); localStorage.setItem('sim-program','"tip-tr"');
      if(st) localStorage.setItem('tpl-t4',JSON.stringify(st)); if(run) localStorage.setItem('tpl-t4-mid',JSON.stringify(run)); },[st,run]);
    await p.goto(base+'#giris'); await p.goto(base+'#now'); await p.reload(); await p.waitForTimeout(300); };
  const nextTxt=async()=>(await p.$('.nownext'))?(await p.textContent('.nownext')).trim():'';
  await p.goto(base+'#now'); await seed(null);
  ok(await p.isVisible('#v-test')&&(await p.getAttribute('#qmode button[data-m="now"]','aria-pressed'))==='true'&&new URL(p.url()).hash==='#now','#now opens the test tab on "Şimdi" (address #now)');
  ok((await p.textContent('#qmode button[data-m="now"]')).trim()==='Şimdi','first mode button is "Şimdi"');
  ok(/Şimdi ne yapacağım/.test(await p.textContent('.nowpage'))&&(await p.textContent('#mycode')).trim()==='PHY-7KQ2','Now page shows title and code box');
  ok(/Sıradaki: Ön test/.test(await nextTxt()),'nothing done: next = pre-test ('+await nextTxt()+')');
  ok(await p.$$eval('.nowrounds .btn',e=>e.length)===2,'2 round chips');
  await p.click('.nownext'); await p.waitForTimeout(200);
  ok(new URL(p.url()).hash==='#pre'&&(await p.getAttribute('#qmode button[data-m="pre"]','aria-pressed'))==='true','next button opens the pre-test (#pre)');
  const t0=Date.now();
  await seed({pre:rec(t0)});
  ok(/Sıradaki: Mini quiz 1/.test(await nextTxt()),'pre done: next = Mini quiz 1');
  ok(/✓ yapıldı/.test(await p.textContent('.nowlist li:first-child')),'pre row shows ✓ done and the total');
  await p.click('.nownext'); await p.waitForTimeout(200);
  ok(new URL(p.url()).hash==='#mid1'&&/Tur 1\/2/.test(await p.textContent('.kh')),'next button opens round 1 (#mid1)');
  await seed({pre:rec(t0),mid1:mrec(t0)});
  ok(/Sıradaki: Mini quiz 2/.test(await nextTxt()),'round 1 done: next = Mini quiz 2');
  ok(await p.$eval('.nowrounds [data-r="1"]',e=>e.classList.contains('done')&&/✓/.test(e.textContent))&&await p.$eval('.nowrounds [data-r="2"]',e=>e.classList.contains('next')),'chip 1 done (✓), chip 2 marked next');
  await p.click('.nowrounds [data-r="1"]'); await p.waitForTimeout(200);
  ok(new URL(p.url()).hash==='#mid1','a done chip can still be opened (#mid1, result)');
  await seed({pre:rec(t0),mid1:mrec(t0)},{r:2,i:0,ans:[],ms:[],ok:[],ph:"q",t0:null});
  ok(/Sıradaki: Mini quiz 2/.test(await nextTxt())||new URL(p.url()).hash==='#mid2','started round 2 comes first');
  await seed({pre:rec(t0),mid1:mrec(t0),mid2:mrec(t0)});
  ok(/Sıradaki: Son test/.test(await nextTxt()),'all rounds done: next = post-test');
  await seed({pre:null,mid1:mrec(t0)});
  ok(/Sıradaki: Ön test/.test(await nextTxt()),'pre not done (round 1 done): next = pre-test');
  await seed({pre:rec(t0),mid1:mrec(t0),post:rec(t0)});
  ok(await nextTxt()===''&&/Şimdilik yapılacak adım yok\. Gecikmeli test .* tarihinde açılır/.test(await p.textContent('.nowpage')),'post done, delayed test not open: no next step, "nothing for now" line with the date');
  ok(await p.$eval('.nowrounds [data-r="2"]',e=>e.classList.contains('closed')),'round 2 closed after the post-test');
  ok(/tarihinde açılır/.test(await p.textContent('.nowlist li:last-child')),'delayed test row shows its opening date');
  ok(/kapalı/.test(await p.textContent('.nowlist li:first-child'))===false,'pre row (done) is not marked closed');
  await seed({pre:rec(t0-20*864e5),post:rec(t0-15*864e5)});
  ok(/Sıradaki: Gecikmeli test/.test(await nextTxt()),'15 days after the post-test: next = delayed test');
  await seed({pre:rec(t0-20*864e5),post:rec(t0-15*864e5),late:rec(t0)});
  ok(await nextTxt()===''&&/bütün adımları tamamlandı/.test(await p.textContent('.nowpage')),'delayed test done: "all steps done" line');
  await seed(null);
  await p.click('#lang button[data-l="en"]'); await p.waitForTimeout(200);
  ok(/Next: Pre-test/.test(await nextTxt())&&/What do I do now/.test(await p.textContent('.nowpage'))&&(await p.textContent('#qmode button[data-m="now"]')).trim()==='Now','English text');
  await p.click('#lang button[data-l="tr"]'); await p.waitForTimeout(100);
  ok(await p.evaluate(()=>document.documentElement.scrollWidth<=document.documentElement.clientWidth),'390 px: no sideways scroll');
  await p.click('.nowlect a'); await p.waitForTimeout(400);
  ok(/^#board1?$/.test(new URL(p.url()).hash)&&await p.isVisible('#board'),'lecturer link opens the leaderboard');
  await p.click('#bclose'); await p.waitForTimeout(200);
  await p.goto(base+'#mid2'); await p.waitForTimeout(200);
  ok(/Tur 2\/2/.test(await p.textContent('.kh')),'old link #mid2 still opens round 2');
  await p.goto(base+'#post'); await p.waitForTimeout(200);
  ok((await p.getAttribute('#qmode button[data-m="post"]','aria-pressed'))==='true','old link #post still works');
  await p.click('#qmode button[data-m="now"]'); await p.waitForTimeout(200);
  ok(new URL(p.url()).hash==='#now'&&await p.isVisible('.nowpage'),'"Şimdi" button returns to the Now page');
  ok(!errs.length,'no page errors '+errs.join(' | '));
  await b.close(); console.log(out.join('\n'));
})().catch(e=>{console.log(out.join('\n')+'\nCRASH '+e.message);});
